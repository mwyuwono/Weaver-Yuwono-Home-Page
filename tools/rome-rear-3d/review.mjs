// Assembles the renders and out/checks.json into a review page and prints it to PDF with headless Chrome.
// Run after build.mjs and render.sh: node review.mjs [renderDir]
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const DIR = path.resolve(process.argv[2] || path.join(HERE, '../../.claude/preview/rome-rear'));
const { checks, cameras } = JSON.parse(fs.readFileSync(path.join(HERE, 'out/checks.json'), 'utf8'));
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;');
const views = [
  ['rear-elevation-proposed', 'Full rear elevation: proposed (orthographic, site and planting hidden)'],
  ['rear-elevation-existing', 'Full rear elevation: existing (as built, A101 + photos)'],
  ['garage-side', `Garage-side view: camera at (${cameras.garageSide.pos[0]}, ${cameras.garageSide.pos[1]}) ft, eye 5.25 ft`],
  ['from-gate', 'From the gate: garage approach, planter and porch west side'],
  ['axo-proposed', 'Overview from the north-east: proposed'],
  ['axo-existing', 'Overview from the north-east: existing'],
  ['plan', 'Courtyard plan: proposed (conceptual planting)'],
];
const html = `<!doctype html><meta charset="utf-8"><title>Rome rear 3D review</title>
<style>
 @page { size: 17in 11in; margin: 0.4in; }
 body { font: 11pt/1.45 Helvetica, Arial, sans-serif; color: #222; margin: 0; }
 section { page-break-after: always; height: 10.1in; display: flex; flex-direction: column; }
 h1 { font-size: 18pt; margin: 0 0 4pt; } h2 { font-size: 12pt; margin: 0 0 8pt; font-weight: normal; color: #555; }
 img { flex: 1; min-height: 0; object-fit: contain; width: 100%; }
 table { border-collapse: collapse; width: 100%; font-size: 9.5pt; } td, th { border-top: 1px solid #ddd; padding: 5pt 6pt; vertical-align: top; text-align: left; }
 .flag { color: #a33; font-weight: bold; } .ok { color: #2a6a3a; font-weight: bold; }
</style>
${views.map(([f, t]) => `<section><h2>${esc(t)}</h2><img src="${f}.png"></section>`).join('\n')}
<section><h1>Design checks</h1><h2>Generated by build.mjs from the same geometry (feet; plan x east, y north, z above courtyard grade)</h2>
<table><tr><th></th><th>Check</th><th>Result</th><th>Note</th></tr>
${checks.map((c) => `<tr><td class="${c.ok ? 'ok' : 'flag'}">${c.ok ? 'OK' : 'FLAG'}</td><td>${esc(c.name)}</td><td>${esc(c.value)}</td><td>${esc(c.note || '')}</td></tr>`).join('\n')}
</table></section>`;
fs.writeFileSync(path.join(DIR, 'review.html'), html);
const chrome = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
execFileSync(chrome, ['--headless=new', '--no-pdf-header-footer', `--print-to-pdf=${path.join(DIR, 'rome-rear-review.pdf')}`, 'file://' + path.join(DIR, 'review.html')], { stdio: 'ignore' });
console.log(path.join(DIR, 'rome-rear-review.pdf'));
